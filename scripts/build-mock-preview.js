const { readFileSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const quiz = require('../mock/quiz.json');
const activity = require('../mock/activities.json');

const validators = readFileSync(join(__dirname, '..', 'api', 'validate.js'), 'utf8');
const preview = { quiz: quiz.response, activity: activity.response };
writeFileSync(
  join(__dirname, '..', 'public', 'js', 'mock-preview.js'),
  `// Generated by npm run preview:mock.\nconst mockPreview = (() => {\n` +
  `const module = { exports: {} };\n${validators}\n` +
  `return { data: ${JSON.stringify(preview, null, 2)}, ...module.exports };\n})();\n`,
);
